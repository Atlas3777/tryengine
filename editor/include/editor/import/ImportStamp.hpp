#pragma once

#include <EASTL/string.h>
#include <EASTL/vector.h>
#include <cstdint>

namespace tryeditor {

// Версия схемы штампа. Поднимай, когда меняется смысл его полей: старые штампы
// перестанут совпадать, и ассеты один раз переимпортируются.
inline constexpr uint32_t kImportStampVersion = 2;

// Файл, прочитанный импортёром помимо исходника: модуль Slang, include и т.п.
// Храним size+mtime, как и для исходника: этого достаточно, чтобы заметить правку,
// и не нужно хешировать содержимое на каждом старте.
struct ImportDependency {
    eastl::string name;  // имя модуля, если оно есть (иначе stem файла)
    eastl::string path;
    uint64_t size = 0;
    int64_t mtime_sec = 0;
    uint64_t mtime_nsec = 0;
};

// Штамп импорта — запись о том, из чего собран артефакт. Лежит рядом с артефактами
// ({artifacts_dir}/stamps/<guid>.json) и сравнивается по содержимому, а не по mtime.
//
// Поэтому порядок асинхронных записей меты и артефактов больше не важен: мета, которую
// импортёр сам же и пишет, не обязана быть ни старше, ни новее артефакта. Достаточно,
// чтобы содержимое меты и исходника совпало с записанным здесь.
//
// В самой мете не хранится ни времени, ни хешей — она остаётся чистым описанием ассета.
struct ImportStamp {
    uint32_t format_version = 0;
    eastl::string importer;         // имя импортёра, которым собран артефакт
    uint32_t importer_version = 0;  // версия его логики, см. IAssetImporter::GetVersion

    // Версия исходника. Хешировать содержимое при каждом старте слишком дорого, поэтому
    // используется пара "размер + mtime". Исходник пишет не конвейер, а пользователь,
    // так что его mtime — честный признак изменения, в отличие от mtime меты/артефакта.
    uint64_t source_size = 0;
    int64_t source_mtime_sec = 0;
    uint64_t source_mtime_nsec = 0;

    // FNV-1a по байтам .meta. Мета уже прочитана при проверке, так что хеш бесплатный,
    // и он ловит именно изменение настроек, а не факт записи файла.
    uint64_t meta_hash = 0;

    // Пути всех записанных артефактов относительно artifacts_dir ("runtime/<main>/<sub>").
    // По ним проверяется, что на диске лежит ровно то, что собрал импорт.
    eastl::vector<eastl::string> artifacts;

    // Внешние зависимости импорта (модули Slang, include-файлы). Правка любой из них
    // делает штамп несовпадающим.
    eastl::vector<ImportDependency> dependencies;
};

}  // namespace tryeditor
